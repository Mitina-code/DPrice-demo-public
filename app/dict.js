// The two supported languages; RU is the default (prototype parity, UX-DR).
export const LANGS = ['ru', 'en'];
const LANG_INDEX = { ru: 0, en: 1 };

// Resolve a message key to text in `lang`. Falls back to the key itself if the
// key is unknown — a visible, debuggable miss rather than a silent blank.
export function t(key, lang) {
  const entry = DICT[key];
  if (!entry) {
    return key;
  }
  return entry[LANG_INDEX[lang] ?? 0];
}

// Resolve a message key to text with its FIRST letter lowercased — for a label
// that reads standalone (capitalized) as a badge or landing but mid-sentence
// (lowercase) inside a phrase. The role titles are the case: «Менеджер по
// ценообразованию» on the badge, but «Требуется роль: менеджер по ценообразованию»
// / «требуется роль {role}» once it follows a colon in the x_requires_role[_tip]
// copy (epics AC5, EXPERIENCE UX-DR3). One capitalized source key, both readings.
export function tlc(key, lang) {
  const text = t(key, lang);
  return text ? text.charAt(0).toLowerCase() + text.slice(1) : text;
}

// Resolve a message key and interpolate `{name}` placeholders from `params` —
// the server sends only the key and its machine params (AD-15), the UI owns both
// the wording and the interpolation. Used for keyed errors carrying a value,
// e.g. x_requires_role's {role}. Missing params leave their placeholder intact,
// a visible miss rather than a silent blank.
export function tp(key, lang, params) {
  let text = t(key, lang);
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}

// Resolve a message key and interpolate POSITIONAL `{0}`, `{1}`, … placeholders
// from the trailing args — the shape the prototype's ~700 D strings use (its
// `t(k, ...)` did the same). Kept alongside `tp` (named params) so the ported
// strings interpolate exactly as they did in the frozen prototype. Surfaces
// (Epic 4) feed it the raw values the payload carries, formatted first through
// the helpers below.
export function tf(key, lang, ...args) {
  let text = t(key, lang);
  args.forEach((value, index) => {
    text = text.split(`{${index}}`).join(String(value));
  });
  return text;
}

// --- number formatting (AD-3): raw numbers in the payload, `Intl` on the client
//
// Locale follows the active language, never the market: ru-RU groups thousands
// with a space and uses a comma decimal; en-US groups with a comma and uses a
// period. A locale-formatted number must never arrive from the server — these
// helpers are the only place a raw payload number becomes display text. They are
// pure: `lang` in, string out, no module-level locale to "swap" (the prototype's
// global LANG becomes an explicit parameter here).

// Map a language code to its `Intl` locale (UX-DR12).
export function localeFor(lang) {
  return lang === 'ru' ? 'ru-RU' : 'en-US';
}

// A plain number with `digits` fraction digits, grouped for the language:
// ru-RU space-thousands + comma-decimals, en-US comma-thousands + period.
export function nf(value, lang, digits = 0) {
  return new Intl.NumberFormat(localeFor(lang), {
    minimumFractionDigits: digits,
    maximumFractionDigits: digits,
  }).format(value);
}

// A ratio as a percent. `digits` defaults to 1 (rates read at 1-2 dp); pass 0
// for probabilities, which render as whole percents (UX-DR12).
export function pct(value, lang, digits = 1) {
  return nf(value * 100, lang, digits) + '%';
}

// A signed change in percentage points, e.g. `+2,0 п.п.` / `+2.0 pp`. The unit
// label is itself a dictionary key (u_pp) so it localizes with everything else.
export function ppt(value, lang, digits = 1) {
  return (value > 0 ? '+' : '') + nf(value * 100, lang, digits) + ' ' + t('u_pp', lang);
}

// A signed plain number, e.g. `+5` / `-5` — the explicit `+` a delta reads with.
export function sgn(value, lang, digits = 0) {
  return (value > 0 ? '+' : '') + nf(value, lang, digits);
}
